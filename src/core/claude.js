/**
 * Claude-side discovery and transcript parsing.
 *
 * Two sources are supported:
 *  - Claude Code / Claude Desktop "local agent" transcripts: JSONL files under
 *    `~/.claude/projects/<project>/<session>.jsonl`.
 *  - Claude account data exports (`conversations.json` from Settings → Privacy →
 *    Export data), which contain every chat of the account.
 */
import fs from 'node:fs';
import path from 'node:path';
import { claudeRoots, readJson } from './paths.js';

const fileCache = new Map();

/** Flatten a Claude message content value into plain text. */
export function textFromContent(content, { includeTools = false } = {}) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  const parts = [];
  for (const block of content) {
    if (!block || typeof block !== 'object') continue;
    if (block.type === 'text' && typeof block.text === 'string') parts.push(block.text);
    else if (block.type === 'thinking' && typeof block.thinking === 'string') continue;
    else if (includeTools && block.type === 'tool_use') {
      parts.push(`[tool ${block.name}] ${JSON.stringify(block.input ?? {})}`);
    }
  }
  return parts.join('\n\n');
}

/** Remove transport noise and harness scaffolding from a message body. */
export function cleanText(text) {
  return String(text)
    .replace(/<system-reminder>[\s\S]*?<\/system-reminder>/gi, '')
    .replace(/\s*API Error: \d{3}[\s\S]*$/i, '')
    .replace(/<local-command-(stdout|stderr)>[\s\S]*?<\/local-command-\1>/gi, '')
    .trim();
}

export function isNoise(text) {
  const t = text.trim();
  if (!t) return true;
  if (/^<system-reminder>/i.test(t)) return true;
  if (/^<command-name>/i.test(t)) return true;
  if (/^<local-command-(stdout|stderr)>/.test(t)) return true;
  if (/^<user-prompt-submit-hook>/i.test(t)) return true;
  if (/^\[Request interrupted by user/i.test(t)) return true;
  if (/^Caveat: The messages below were generated by the user while running local commands/i.test(t)) return true;
  if (/^No response requested\.?$/i.test(t)) return true;
  if (/^This session is being continued from a previous conversation/i.test(t)) return false;
  return false;
}

/** Group a flat list of messages into `{ user, assistant[] }` turns. */
export function toTurns(flat) {
  const turns = [];
  for (const item of flat) {
    if (item.role === 'user') turns.push({ user: item.text, assistant: [] });
    else if (turns.length > 0) turns[turns.length - 1].assistant.push(item.text);
  }
  return turns.filter((turn) => turn.user && turn.assistant.length > 0);
}

function emptyStats() {
  return { messages: 0, userMessages: 0, assistantMessages: 0, toolCalls: 0, chars: 0, turns: 0, sidechains: 0 };
}

/** Parse one Claude Code JSONL transcript. */
export function parseClaudeCodeFile(file, { includeTools = false } = {}) {
  const stat = fs.statSync(file);
  const cached = fileCache.get(file);
  if (cached && cached.mtimeMs === stat.mtimeMs && cached.size === stat.size && cached.includeTools === includeTools) {
    return cached.value;
  }

  const raw = fs.readFileSync(file, 'utf8');
  const stats = emptyStats();
  const flat = [];
  let cwd = '';
  let entrypoint = '';
  let sessionId = path.basename(file, '.jsonl');
  let firstTimestamp = null;
  let lastTimestamp = null;
  let version = '';

  for (const line of raw.split('\n')) {
    if (!line.trim()) continue;
    let rec;
    try {
      rec = JSON.parse(line);
    } catch {
      continue;
    }
    if (rec.sessionId) sessionId = rec.sessionId;
    if (rec.cwd && !cwd) cwd = rec.cwd;
    if (rec.entrypoint) entrypoint = rec.entrypoint;
    if (rec.version) version = rec.version;
    if (rec.timestamp) {
      if (!firstTimestamp) firstTimestamp = rec.timestamp;
      lastTimestamp = rec.timestamp;
    }
    if (rec.type !== 'user' && rec.type !== 'assistant') continue;
    const message = rec.message;
    if (!message) continue;
    if (rec.isSidechain === true) stats.sidechains += 1;
    if (rec.isSidechain === true || rec.isMeta === true) continue;

    if (message.role === 'user') {
      const text = cleanText(textFromContent(message.content, { includeTools }));
      if (isNoise(text)) continue;
      stats.userMessages += 1;
      stats.chars += text.length;
      flat.push({ role: 'user', text });
    } else if (message.role === 'assistant') {
      if (Array.isArray(message.content)) {
        for (const block of message.content) {
          if (block && block.type === 'tool_use') stats.toolCalls += 1;
        }
      }
      const text = cleanText(textFromContent(message.content, { includeTools }));
      if (isNoise(text)) continue;
      stats.assistantMessages += 1;
      stats.chars += text.length;
      flat.push({ role: 'assistant', text });
    }
    stats.messages += 1;
  }

  const turns = toTurns(flat);
  stats.turns = turns.length;
  const firstPrompt = turns.find((turn) => !/^This session is being continued/i.test(turn.user))?.user || turns[0]?.user || '';

  const value = {
    sessionId,
    cwd,
    entrypoint,
    version,
    firstTimestamp,
    lastTimestamp,
    firstPrompt: firstPrompt.replace(/\s+/g, ' ').slice(0, 400),
    stats,
    turns,
  };
  fileCache.set(file, { mtimeMs: stat.mtimeMs, size: stat.size, includeTools, value });
  return value;
}

/** Decode a Claude Code project directory name back to a hint path. */
function projectHint(folder) {
  if (!folder.startsWith('C--')) return folder;
  const relaxed = folder.replace(/^C--/, 'C:\\').replace(/-/g, '\\');
  return relaxed;
}

/** List every locally discoverable Claude Code session. */
export function discoverClaudeSessions({ includeSidechains = false } = {}) {
  const roots = claudeRoots();
  const out = [];
  if (!fs.existsSync(roots.projects)) return out;

  for (const project of fs.readdirSync(roots.projects, { withFileTypes: true })) {
    if (!project.isDirectory()) continue;
    const projectDir = path.join(roots.projects, project.name);
    for (const entry of fs.readdirSync(projectDir, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith('.jsonl')) continue;
      const isAgentFile = entry.name.startsWith('agent-');
      const file = path.join(projectDir, entry.name);
      let parsed;
      try {
        parsed = parseClaudeCodeFile(file);
      } catch {
        continue;
      }
      if (isAgentFile && !includeSidechains) continue;
      const stat = fs.statSync(file);
      out.push({
        id: path.basename(entry.name, '.jsonl'),
        source: 'claude-code',
        sourceLabel: 'Claude Code',
        file,
        name: `${parsed.firstPrompt.slice(0, 80) || path.basename(entry.name, '.jsonl')}`,
        project: project.name,
        projectHint: parsed.cwd || projectHint(project.name),
        cwd: parsed.cwd,
        entrypoint: parsed.entrypoint || '',
        sizeBytes: stat.size,
        mtime: stat.mtime.toISOString(),
        firstTimestamp: parsed.firstTimestamp,
        lastTimestamp: parsed.lastTimestamp,
        stats: parsed.stats,
        badge: isAgentFile ? 'subagent' : '',
      });
    }
  }
  out.sort((a, b) => (a.mtime < b.mtime ? 1 : -1));
  return out;
}

/** Parse a Claude account data export (`conversations.json`). */
export function parseClaudeExport(json) {
  const list = Array.isArray(json) ? json : Array.isArray(json?.conversations) ? json.conversations : [];
  const sessions = [];
  for (const conversation of list) {
    const messages = conversation.chat_messages || conversation.messages || [];
    const flat = [];
    for (const message of messages) {
      const role = message.sender === 'human' || message.role === 'user' ? 'user' : 'assistant';
      const text = cleanText(
        message.text || textFromContent(message.content) || textFromContent(message.attachments),
      );
      if (isNoise(text)) continue;
      flat.push({ role, text });
    }
    const turns = toTurns(flat);
    if (turns.length === 0) continue;
    const chars = turns.reduce(
      (sum, turn) => sum + turn.user.length + turn.assistant.join('\n\n').length,
      0,
    );
    sessions.push({
      id: conversation.uuid || conversation.id || `export-${sessions.length + 1}`,
      source: 'claude-export',
      sourceLabel: 'Claude export',
      name: conversation.name || turns[0].user.slice(0, 80),
      project: 'Claude account export',
      projectHint: '',
      cwd: '',
      entrypoint: 'export',
      sizeBytes: JSON.stringify(conversation).length,
      mtime: conversation.updated_at || conversation.created_at || new Date().toISOString(),
      stats: {
        ...emptyStats(),
        turns: turns.length,
        messages: flat.length,
        userMessages: turns.length,
        assistantMessages: turns.length,
        chars,
      },
      turns,
    });
  }
  sessions.sort((a, b) => (a.mtime < b.mtime ? 1 : -1));
  return sessions;
}
